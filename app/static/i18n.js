let currentLang = "en";

function confirmWord() { return currentLang === "fr" ? "SUPPRIMER" : "DELETE"; }

function t(key, vars) {
  let s = (I18N[currentLang] && I18N[currentLang][key]) || I18N.fr[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v ?? ""));
  }
  return s;
}

function applyI18n() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.dispatchEvent(new CustomEvent("langchange"));
}

function setLang(lang, persist = true) {
  currentLang = I18N[lang] ? lang : "fr";
  if (persist) { try { localStorage.setItem("sp-lang", currentLang); } catch (e) { /* ignore */ } }
  applyI18n();
}

function initLang(fallback) {
  let lang = null;
  try { lang = localStorage.getItem("sp-lang"); } catch (e) { /* ignore */ }
  currentLang = (lang && I18N[lang]) ? lang : ((fallback && I18N[fallback]) ? fallback : "en");
  applyI18n();
  return currentLang;
}
